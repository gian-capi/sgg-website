/* Signature Gallery Group — first-party analytics.
   Generated by the SGG Admin Manager. Edits here are overwritten on publish. */
(function () {
  'use strict';

  var ENDPOINT = "http://localhost:4000" + '/collect';

  function id() {
    return (Date.now().toString(36) + Math.random().toString(36).slice(2, 10));
  }

  function store(area, key) {
    try {
      var v = window[area].getItem(key);
      if (!v) { v = id(); window[area].setItem(key, v); }
      return v;
    } catch (e) { return ''; }
  }

  var vid = store('localStorage', 'sgg_vid');
  var sid = store('sessionStorage', 'sgg_sid');
  var PATH = location.pathname + location.search;

  function send(route, body, useBeacon) {
    body.vid = vid; body.sid = sid;
    var url = ENDPOINT + route;
    var json = JSON.stringify(body);
    if (useBeacon && navigator.sendBeacon) {
      navigator.sendBeacon(url, new Blob([json], { type: 'application/json' }));
      return Promise.resolve();
    }
    return fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: json,
      keepalive: true,
      mode: 'cors'
    }).catch(function () {});
  }

  // ---- pageview -----------------------------------------------------------
  send('/view', { path: PATH, referrer: document.referrer || '' });

  // ---- interactions -------------------------------------------------------
  function track(name, extra) {
    var body = { name: name, path: PATH };
    for (var k in extra) if (Object.prototype.hasOwnProperty.call(extra, k)) body[k] = extra[k];
    send('/event', body, true);
  }

  document.addEventListener('click', function (e) {
    var el = e.target.closest ? e.target.closest('a, [data-lb-src], .btn-pill, .btn-ghost') : null;
    if (!el) return;

    // Artwork lightbox opens are the strongest interest signal on the site.
    var lb = el.getAttribute && el.getAttribute('data-lb-src');
    if (lb) {
      track('artwork_open', {
        artwork: lb.replace(/^(\.\.\/)+/, ''),
        label: el.getAttribute('data-lb-caption') || ''
      });
      return;
    }

    var href = el.getAttribute && el.getAttribute('href');
    if (!href) return;

    if (href.indexOf('tel:') === 0) return track('phone_click', { label: href.slice(4) });
    if (href.indexOf('mailto:') === 0) return track('email_click', { label: href.slice(7).split('?')[0] });

    if (el.classList && (el.classList.contains('btn-pill') || el.classList.contains('btn-ghost'))) {
      return track('cta_click', { label: (el.textContent || '').trim().slice(0, 80) });
    }

    if (/^https?:\/\//.test(href) && href.indexOf(location.host) === -1) {
      return track('outbound', { label: href });
    }
  }, true);

  // ---- newsletter / contact capture --------------------------------------
  document.querySelectorAll('form[data-sgg-signup]').forEach(function (form) {
    form.addEventListener('submit', function (e) {
      e.preventDefault();
      var input = form.querySelector('input[type="email"]');
      var msg = form.querySelector('[data-sgg-signup-msg]');
      var email = input && input.value.trim();
      if (!email) return;

      function say(text) {
        if (!msg) return;
        msg.textContent = text;
        msg.hidden = false;
      }

      fetch(ENDPOINT + '/inquiry', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ email: email, type: 'Newsletter', path: PATH, vid: vid, sid: sid }),
        mode: 'cors'
      })
        .then(function (r) {
          if (!r.ok) throw new Error('rejected');
          form.reset();
          say('Thank you — you are on the list.');
        })
        .catch(function () {
          say('Sorry, that did not go through. Please email ' + 'info@signaturegalleries.com' + '.');
        });
    });
  });
})();
